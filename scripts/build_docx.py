def set_font(run, cn=CN_FONT, size=12, bold=False, color=None):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.font.bold = bold
    r = run._element.rPr.rFonts
    r.set(qn("w:eastAsia"), cn)
    if color:
        run.font.color.rgb = RGBColor(*color)


def para(text="", size=12, bold=False, cn=CN_FONT, indent=True, align=None, space_after=6, color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY
    pf.line_spacing = Pt(22)
    if indent:
        pf.first_line_indent = Pt(24)  # 首行缩进 2 字符
    pf.space_after = Pt(space_after)
    if align:
        pf.alignment = align
    if text:
        set_font(p.add_run(text), cn=cn, size=size, bold=bold, color=color)
    return p


def heading(text, level):
    sizes = {1: 16, 2: 14, 3: 13}
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(10)
    pf.space_after = Pt(8)
    pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY
    pf.line_spacing = Pt(24)
    set_font(p.add_run(text), cn=HEAD_FONT, size=sizes.get(level, 12), bold=True)
    return p


def table(rows, widths=None, header=True):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.text = ""
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            set_font(p.add_run(str(val)), size=10.5, bold=(header and i == 0))
    if widths:
        for j, w in enumerate(widths):
            for i in range(len(rows)):
                t.cell(i, j).width = Cm(w)
    return t


def pic(name, width_cm=11.5, caption=None):
    path = os.path.join(SHOT, name)
    if os.path.exists(path):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(path, width=Cm(width_cm))
        if caption:
            c = doc.add_paragraph()
            c.alignment = WD_ALIGN_PARAGRAPH.CENTER
            set_font(c.add_run(caption), size=9, color=(0x60, 0x60, 0x60))
    else:
        para("【截图缺失】" + name, size=10, color=(0xCC, 0, 0))


